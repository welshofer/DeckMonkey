import Foundation
import SwiftProtobuf
import SwiftProtobufPluginLibrary

/// Step 5 of the schema pipeline: the type-number → generated-Swift-type switch, and the union of
/// every file's extension map, from the registry JSON plus the descriptors.
///
/// Swift names come from SwiftProtobufNamer, the same namer protoc-gen-swift used, so nesting,
/// package prefixes and reserved-word escaping can never drift from the generated code. The
/// extension maps are the `…_Extensions` constants protoc-gen-swift emitted, read back from the
/// generated directory.
enum DispatchTable {
    enum Failure: Error, CustomStringConvertible {
        case unknownMessage(type: UInt32, name: String)

        var description: String {
            switch self {
            case .unknownMessage(let type, let name): return "registry type \(type) names \(name), which no descriptor defines"
            }
        }
    }

    struct Registry: Decodable {
        let keynoteVersion: String
        let keynoteBuild: String?
        let types: [String: String]
    }

    static func run(descriptors: URL, registry: URL, generated: URL, out: URL) throws -> Int {
        let set = try Google_Protobuf_FileDescriptorSet(serializedBytes: Data(contentsOf: descriptors))
        let pool = DescriptorSet(protos: set.file.map(Generate.withJSONNames))
        let namer = SwiftProtobufNamer()
        let reg = try JSONDecoder().decode(Registry.self, from: Data(contentsOf: registry))

        var cases = [(UInt32, String, String)]()
        for (key, name) in reg.types {
            guard let type = UInt32(key) else { continue }
            guard let message = pool.descriptor(named: name) else { throw Failure.unknownMessage(type: type, name: name) }
            cases.append((type, name, namer.fullName(message: message)))
        }
        cases.sort { $0.0 < $1.0 }

        var maps = [String]()
        let pattern = try NSRegularExpression(pattern: #"public nonisolated let (\w+_Extensions): SwiftProtobuf\.SimpleExtensionMap"#)
        for file in try FileManager.default.contentsOfDirectory(atPath: generated.path).sorted() where file.hasSuffix(".pb.swift") {
            let text = try String(contentsOf: generated.appendingPathComponent(file), encoding: .utf8)
            for match in pattern.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
                maps.append(String(text[Range(match.range(at: 1), in: text)!]))
            }
        }

        let build = reg.keynoteBuild.map { " (\($0))" } ?? ""
        var source = """
            // Generated by Scripts/schema/protodump dispatch from registry-\(reg.keynoteVersion).json and the
            // descriptors extracted from Keynote \(reg.keynoteVersion)\(build). Do not edit; run `make schema`.

            import SwiftProtobuf

            /// The generated message type for each type number Keynote \(reg.keynoteVersion) registers
            /// (\(cases.count) types), and every extension its schema declares.
            public enum Schema {
                public static let keynoteVersion = "\(reg.keynoteVersion)"

                /// Every file's extensions, for decoding payloads that carry them.
                public static let extensions: SimpleExtensionMap = {
                    var map = SimpleExtensionMap()

            """
        for name in maps { source += "        map.formUnion(\(name))\n" }
        source += """
                    return map
                }()

                public static func messageType(for type: UInt32) -> (any SwiftProtobuf.Message.Type)? {
                    switch type {

            """
        for (type, name, swift) in cases { source += "        case \(type): return \(swift).self  // \(name)\n" }
        source += """
                    default: return nil
                    }
                }
            }

            """
        try Data(source.utf8).write(to: out)
        return cases.count
    }
}
