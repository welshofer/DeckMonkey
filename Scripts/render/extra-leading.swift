// extra-leading.swift — the faces macOS sets with extra leading, as Swift source.
//
// usage: swift Scripts/render/extra-leading.swift > Sources/KeynoteRender/ExtraLeadingFaces.swift
//
// AppKit (and Keynote, whose text matches it) gives some faces with no line gap a fifth of their
// ascent plus descent as leading, above each line: Palatino, Times, Helvetica, Hoefler Text,
// Courier, Proxima Nova and some 300 others, by a rule no font table field explains (Georgia and
// Baskerville, with the same table shapes, get none). This asks NSLayoutManager for every face
// installed, downloadable ones included once downloaded, and writes those it pads. macOS only.
import AppKit

var names = Set<String>()
for name in NSFontManager.shared.availableFonts {
    guard let font = NSFont(name: name, size: 100) else { continue }
    let ct = font as CTFont
    let plain = CTFontGetAscent(ct).rounded() + CTFontGetDescent(ct).rounded() + CTFontGetLeading(ct).rounded()
    if NSLayoutManager().defaultLineHeight(for: font) - plain > 0.5 { names.insert(name) }
}
print("""
// Generated by Scripts/render/extra-leading.swift on macOS: do not edit.

extension Canvas {
    /// Faces set with a fifth of their ascent plus descent as leading above each line.
    static let extraLeadingFaces: Set<String> = [
""")
for name in names.sorted() { print("        \"\(name)\",") }
print("""
    ]
}
""")
